test('legacy community adoption proves both identities and prevents profile takeover',async t=>{
 const dir=mkdtempSync(join(tmpdir(),'branche-adopt-'));
 const store=await openStore({directory:join(dir,'community'),databaseUrl:''});
 const password='legacy profile password 2026';
 await store.query('INSERT INTO branche_users VALUES(?,?,?,?,?,?,?,?)',['legacy','legacy@example.test','Legacy Owner','contractor','salt',scryptSync(password,'salt',32).toString('hex'),termsVersion,Date.now()]);
 await store.query('INSERT INTO branche_posts VALUES(?,?,?,?,?,?,?,?)',['saved-post','legacy','Saved update','Carpentry','Mentor','Keep this saved update','published',Date.now()]);
 const server=createProduct({dataDir:dir,communityOptions:{}});server.listen(0,'127.0.0.1');await once(server,'listening');
 t.after(async()=>{await new Promise(resolve=>{server.close(resolve);server.closeIdleConnections();});await store.close();});
 const base='http://127.0.0.1:'+server.address().port;
 const call=async(path,body,cookie='')=>{const r=await fetch(base+path,{method:body?'POST':'GET',headers:{origin:base,cookie,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};};
 const signup=email=>call('/api/branche/register',{name:'Shared Owner',email,password:'shared account password 2026',terms:termsVersion,role:'contractor'});
 const a=await signup('legacy@example.test'),b=await signup('other@example.test');
 assert.notEqual(a.data.user.id,'legacy','Matching email never proves old profile ownership');
 assert.equal((await call('/api/branche/adopt-profile',{email:'legacy@example.test',password:'wrong'},a.cookie)).status,401);
 assert.equal((await call('/api/branche/adopt-profile',{email:'legacy@example.test',password},a.cookie)).status,200);
 assert.equal((await call('/api/branche/session',null,a.cookie)).data.user.id,'legacy');
 assert.equal((await call('/api/branche/posts',null,a.cookie)).data.posts[0].id,'saved-post');
 assert.equal((await call('/api/branche/adopt-profile',{email:'legacy@example.test',password},b.cookie)).status,409);
});
test('one origin and one session: community registration, tools, isolation and global logout',async t=>{
 const server=createProduct({dataDir:mkdtempSync(join(tmpdir(),'branche-unified-')),communityOptions:{}});
 server.listen(0,'127.0.0.1');await once(server,'listening');
 t.after(()=>new Promise(resolve=>{server.close(resolve);server.closeIdleConnections();}));
 const base='http://127.0.0.1:'+server.address().port;
 const call=async(path,body,cookie='',origin=base)=>{const r=await fetch(base+path,{method:body?'POST':'GET',headers:{origin,cookie,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});return {status:r.status,data:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};};
 const owner=await call('/api/branche/register',{name:'Owner',email:'one@example.test',role:'contractor',terms:termsVersion,password:'one shared long passphrase'});
 assert.equal(owner.status,201,JSON.stringify(owner.data));assert.match(owner.cookie,/^jobscopes_session=/);
 const community=await call('/api/branche/session',null,owner.cookie);assert.equal(community.data.user.id,owner.data.user.id);assert.equal(community.data.unified,true);
 const tools=await call('/api/account/session',null,owner.cookie);assert.equal(tools.data.user.email,'one@example.test');
 const project=await call('/api/projects',{name:'Shared session project',type:'Deck',status:'Planning'},owner.cookie);assert.equal(project.status,201);
 const link=await call('/api/branche/workspace',null,owner.cookie);assert.equal(link.data.url,'/');assert.equal(link.data.workspace.name,tools.data.company.name);
 const other=await call('/api/branche/register',{name:'Customer',email:'two@example.test',role:'customer',terms:termsVersion,password:'another shared long password'});
 assert.equal(other.status,201);assert.equal(other.data.user.role,'customer');assert.notEqual(other.data.user.id,owner.data.user.id);
 assert.equal((await call('/api/branche/business-role',{},other.cookie)).status,200);
 assert.equal((await call('/api/branche/session',null,other.cookie)).data.user.role,'contractor');
 assert.equal((await call('/api/branche/business-role',{})).status,401);
 assert.notEqual((await call('/api/account/session',null,other.cookie)).data.company.id,tools.data.company.id);
 assert.equal((await call('/api/branche/logout',{},owner.cookie,'https://evil.example')).status,403);
 assert.equal((await call('/api/branche/logout',{},owner.cookie)).status,200);
 assert.equal((await call('/api/account/session',null,owner.cookie)).data.user,null);
 assert.equal((await call('/api/branche/session',null,owner.cookie)).data.user,null);
 const login=await call('/api/account/login',{email:'one@example.test',password:'one shared long passphrase'});
 assert.equal(login.status,200);assert.equal((await call('/api/branche/session',null,login.cookie)).data.user.id,owner.data.user.id);
 assert.equal((await call('/api/account/logout',{},login.cookie)).status,200);
 assert.equal((await call('/api/branche/session',null,login.cookie)).data.user,null);
 for(const path of ['/community/','/community/app.js','/community/style.css'])assert.equal((await fetch(base+path)).status,200);
 const shell=await (await fetch(base+'/')).text();assert.ok(shell.includes('href="/community/"'));assert.ok(!shell.includes('https://branche-test'));
 const communityShell=await (await fetch(base+'/community/')).text();assert.ok(communityShell.includes('src="/community/app.js"'));
});
