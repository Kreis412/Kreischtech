import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {once} from 'node:events';
import {DatabaseSync} from 'node:sqlite';
import {createProduct} from '../server.mjs';
test('delete project is confirmed, company scoped, removes private content and preserves company accounting',async t=>{
 const dir=mkdtempSync(join(tmpdir(),'cs-delete-')),server=createProduct({dataDir:dir});
 server.listen(0,'127.0.0.1');await once(server,'listening');
 t.after(async()=>{await new Promise(r=>server.close(r));rmSync(dir,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+server.address().port;
 const client=()=>({cookie:'',async call(path,method='GET',body,status=200){
  const r=await fetch(base+path,{method,headers:{cookie:this.cookie,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});
  if(r.headers.get('set-cookie'))this.cookie=r.headers.get('set-cookie').split(';')[0];
  const data=await r.json();assert.equal(r.status,status,JSON.stringify(data));return data;
 }});
 const a=client(),b=client(),v=client();
 for(const [c,email] of [[a,'a'],[b,'b'],[v,'v']])await c.call('/api/account/register','POST',{name:email,email:email+'@example.test',company:email,password:'Test-delete-only-456789!'},201);
 const company=(await a.call('/api/account/session')).company;
 const inv=await a.call('/api/account/invites','POST',{email:'v@example.test',role:'Viewer'},201);
 await v.call('/api/account/join','POST',{code:inv.code});await v.call('/api/account/switch','POST',{company_id:company.id});
 const p=await a.call('/api/projects','POST',{name:'Disposable demo',type:'Basement',status:'Planning'},201);
 const keep=await a.call('/api/projects','POST',{name:'Keep me',type:'Basement',status:'Planning'},201);
 const png=Buffer.from('89504e470d0a1a0a00000000','hex');
 const uploaded=await fetch(base+'/api/projects/'+p.id+'/photos?name=demo.png',{method:'POST',headers:{cookie:a.cookie},body:png});assert.equal(uploaded.status,201);const photo=await uploaded.json();
 await a.call('/api/company/entries','POST',{entry_date:'2026-01-01',type:'Payment received',category:'Other',amount:'2500',description:'Receipt',status:'Recorded',project_id:p.id},201);
 const portal=await a.call('/api/projects/'+p.id+'/customer-portal','POST',{title:'Demo',status:'Planning',progress:0,photos:[photo.id]},200);
 const db=new DatabaseSync(join(dir,'companies',company.id,'contractoros.sqlite'));
 db.prepare('INSERT INTO photo_measurements VALUES(?,?,1)').run(photo.id,'[]');
 db.prepare('INSERT INTO joe_exchanges VALUES(?,?,?,?,?,?,?,?)').run('exchange','a',p.id,'Q','A','null','test','now');
 db.prepare('INSERT INTO equipment VALUES(?,?,?,1)').run('truck','TR',JSON.stringify({project_id:p.id,status:'Assigned'}));
 db.close();
 const body={confirm_name:p.name,revision:p.revision};
 await b.call('/api/projects/'+p.id,'DELETE',body,404);
 await v.call('/api/projects/'+p.id,'DELETE',body,403);
 await a.call('/api/projects/'+p.id,'DELETE',{...body,confirm_name:'wrong'},400);
 await a.call('/api/projects/'+p.id,'DELETE',{...body,revision:0},409);
 await a.call('/api/projects/'+p.id,'DELETE',body);
 await a.call('/api/projects/'+p.id,'GET',undefined,404);await a.call('/api/photos/'+photo.id,'GET',undefined,404);
 assert.equal((await a.call('/api/projects')).length,1);assert.equal((await a.call('/api/projects/'+keep.id)).name,'Keep me');
 const publicStatus=await fetch(base+'/api/customer',{headers:{'X-Customer-Token':portal.token}});assert.equal(publicStatus.status,404);
 const check=new DatabaseSync(join(dir,'companies',company.id,'contractoros.sqlite'));
 assert.equal(check.prepare('SELECT count(*) n FROM joe_exchanges').get().n,0);
 assert.equal(check.prepare('SELECT count(*) n FROM photo_measurements').get().n,0);
 assert.equal(check.prepare('SELECT project_id FROM cash_entries').get().project_id,null);
 assert.equal(check.prepare('SELECT amount_cents FROM cash_entries').get().amount_cents,250000);
 assert.equal(JSON.parse(check.prepare('SELECT data FROM equipment').get().data).status,'Available');
 assert.deepEqual(check.prepare('PRAGMA foreign_key_check').all(),[]);check.close();
});
